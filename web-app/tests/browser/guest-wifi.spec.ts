import { test, expect } from './support/harness'
import { openApp, VIEWPORTS } from './support/app'
import { guestWifi } from './support/fixtures'
const path = '/cgi-bin/guest-wifi'
test('stock duration choices, remaining time and disabled radio are visible without writes', async ({ page, agent }) => {
  await openApp(page, { group: 'network', tab: 'Wi-Fi' })
  const section = page.getByRole('region', { name: '访客 Wi-Fi 设置' })
  await expect(section.getByText('访客 Wi-Fi 总开关', { exact: true })).toBeVisible()
  await expect(section.getByText('允许访客访问局域网', { exact: true })).toBeVisible()
  await expect(section.getByLabel('访客开放时长').locator('option')).toHaveText(['不限时', '2 小时', '4 小时', '8 小时', '12 小时', '1 天'])
  await expect(section.getByText('2.4 GHz 总无线已关闭', { exact: false })).toBeVisible()
  await expect(section.getByText('剩余 2 小时 0 分钟', { exact: false })).toHaveCount(2)
  expect(agent.mutations()).toEqual([])
})
test('guest edits are drafts; Cancel sends nothing; Confirm sends only the chosen guest band', async ({ page, agent }) => {
  agent.on('POST', path, { data: guestWifi() })
  await openApp(page, { group: 'network', tab: 'Wi-Fi' })
  await page.getByRole('button', { name: '编辑访客 5 GHz', exact: true }).click()
  await page.getByLabel('访客 5 GHz 名称', { exact: true }).fill('New Guest')
  await page.getByLabel('访客 5 GHz 密码', { exact: true }).fill('Synthetic123')
  expect(agent.mutations()).toEqual([])
  await page.getByRole('button', { name: '保存访客 5 GHz', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toContainText('Synthetic123')
  await page.getByRole('dialog').getByRole('button', { name: '取消' }).click()
  expect(agent.mutations()).toEqual([])
  await expect(page.getByLabel('访客 5 GHz 名称', { exact: true })).toHaveValue('New Guest')
  await page.getByRole('button', { name: '保存访客 5 GHz', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click()
  await expect.poll(() => agent.mutations().length).toBe(1)
  expect(agent.mutations()[0].path).toBe(path)
  expect(agent.mutations()[0].body).toMatchObject({ band: '5g', settings: { ssid: 'New Guest', password: 'Synthetic123' } })
})
test('duration uses the stock hours and LAN access is independently confirmed', async ({ page, agent }) => {
  agent.on('POST', path, { data: guestWifi() })
  await openApp(page, { group: 'network', tab: 'Wi-Fi' })
  await page.getByLabel('访客开放时长').selectOption('8')
  await page.getByRole('button', { name: '应用开放时长' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click()
  await expect.poll(() => agent.mutations().length).toBe(1)
  expect(agent.mutations()[0].body).toEqual({ duration_hours: 8 })
  await page.getByRole('switch', { name: '允许访客访问局域网' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click()
  await expect.poll(() => agent.mutations().length).toBe(2)
  expect(agent.mutations()[1].body).toEqual({ lan_access: true })
})
test('failed saves retain drafts; short passwords cannot be submitted', async ({ page, agent }) => {
  agent.on('POST', path, { error: 'synthetic guest failure', status: 503 })
  await openApp(page, { group: 'network', tab: 'Wi-Fi' })
  await page.getByRole('button', { name: '编辑访客 5 GHz', exact: true }).click()
  await page.getByLabel('访客 5 GHz 密码', { exact: true }).fill('short')
  await expect(page.getByRole('button', { name: '保存访客 5 GHz', exact: true })).toBeDisabled()
  await page.getByLabel('访客 5 GHz 密码', { exact: true }).fill('Synthetic123')
  await page.getByRole('button', { name: '保存访客 5 GHz', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.getByText('synthetic guest failure')).toBeVisible()
  await expect(page.getByLabel('访客 5 GHz 密码', { exact: true })).toHaveValue('Synthetic123')
  expect(agent.mutations()).toHaveLength(1)
})
